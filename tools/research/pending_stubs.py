"""Generate src/game/pending_stubs.cpp: a logging stub for every function declared in
src/game/game_flight.h that has no definition in src/game/*.cpp yet (slice S5 block B and later
are translated in pieces; the stubs keep the build linking until each function is translated).

Usage: python tools/research/pending_stubs.py   (run from the repository root)
Prints the number of stubs. The stub logs once ("not translated yet") and returns 0.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HDR = os.path.join(ROOT, "src", "game", "game_flight.h")
OUT = os.path.join(ROOT, "src", "game", "pending_stubs.cpp")

DECL = re.compile(r"^([A-Za-z_][\w:<>]*\s*\**)\s+([A-Za-z_]\w*)\(([^)]*)\);", re.M)


def defined_names():
    names = set()
    for f in glob.glob(os.path.join(ROOT, "src", "game", "*.cpp")):
        if os.path.abspath(f) == OUT:
            continue
        src = open(f, encoding="utf-8").read()
        for m in re.finditer(r"^[A-Za-z_][\w:<> ]*?[\s*&]([A-Za-z_]\w*)\(([^;{]*?)\)\s*(?:const\s*)?\{", src, re.M):
            names.add(m.group(1))
    return names


def main():
    hdr = open(HDR, encoding="utf-8").read()
    have = defined_names()
    out = [
        "// GENERATED by tools/research/pending_stubs.py: logging stubs for the scene 2 functions declared in",
        "// game_flight.h that are not translated yet. Do not edit; rerun the tool after translating.",
        '#include "game/game.h"',
        "",
        '#include "platform/log.h"',
        "",
        "namespace ac04::game {",
        "",
        "namespace {",
        "void Pending(const char* name) {",
        '    log::WriteOnce(name, log::Level::Info, "game", "scene 2: %s not translated yet", name);',
        "}",
        "}  // namespace",
        "",
    ]
    n = 0
    for m in DECL.finditer(hdr):
        ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
        if name in have:
            continue
        n += 1
        plist = []
        for i, p in enumerate([x.strip() for x in params.split(",") if x.strip() and x.strip() != "void"]):
            t = re.sub(r"\s*\b\w+$", "", p) if re.search(r"\s\w+$", p) else p
            plist.append(f"{t} /*a{i}*/")
        body = f'Pending("{name}");'
        if ret != "void":
            body += " return {};"
        out.append(f"{ret} {name}({', '.join(plist)}) {{ {body} }}")
    out += ["", "}  // namespace ac04::game", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"{n} pending stubs -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
